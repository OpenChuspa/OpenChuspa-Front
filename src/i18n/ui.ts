export type UIKey = keyof (typeof ui)['es'];

export function useT(lang: Lang) {
  return (key: UIKey, vars: Record<string, string> = {}) =>
    (ui[lang][key] as string).replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? `{${k}}`);
}

