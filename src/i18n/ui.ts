// Textos de la interfaz en cada idioma. El español es el idioma por defecto
// (rutas sin prefijo); el inglés vive bajo /en/.
export const languages = { es: 'Español', en: 'English' } as const;
export type Lang = keyof typeof languages;
export const defaultLang: Lang = 'es';

export function getLang(locale: string | undefined): Lang {
  return locale === 'en' ? 'en' : 'es';
}

/** Ruta de una página en el idioma pedido: '/docs/' → '/en/docs/'. */
export function localizePath(path: string, lang: Lang): string {
  const bare = path.replace(/^\/en(?=\/|$)/, '') || '/';
  return lang === defaultLang ? bare : `/en${bare === '/' ? '/' : bare}`;
}

